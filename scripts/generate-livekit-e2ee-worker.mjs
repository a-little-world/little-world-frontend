// Metro can't emit worker chunks or resolve import.meta.url, so the native build starts
// the livekit E2EE worker from this inlined source instead.
import { readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const prebuildDir = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '../prebuild',
);

const workerPath = require.resolve('livekit-client/e2ee-worker');
const workerSource = readFileSync(workerPath, 'utf8');
const { version } = JSON.parse(
  readFileSync(path.resolve(workerPath, '../../package.json'), 'utf8'),
);
const name = `livekit-e2ee-worker-${version}`;

// workers of other livekit-client versions
readdirSync(prebuildDir)
  .filter(
    file =>
      file.startsWith('livekit-e2ee-worker-') && !file.startsWith(`${name}.`),
  )
  .forEach(file => rmSync(path.join(prebuildDir, file)));

writeFileSync(
  path.join(prebuildDir, `${name}.js`),
  `// Generated by scripts/generate-livekit-e2ee-worker.mjs from livekit-client@${version} — do not edit.\n` +
    `export default ${JSON.stringify(workerSource)};\n`,
);
writeFileSync(
  path.join(prebuildDir, `${name}.d.ts`),
  'declare const workerSource: string;\nexport default workerSource;\n',
);

console.log(`[generate-livekit-e2ee-worker] wrote prebuild/${name}.js`);
